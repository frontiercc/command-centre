-- Monthly spot-check of the estimates (20 per surface). No person column: a
-- row says which session was checked and the verdict; who reviewed is in the
-- access log. The estimate is copied in, so the check still reads after the
-- session itself has been pruned by retention.
CREATE TABLE IF NOT EXISTS human_time_checks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  surface TEXT NOT NULL,
  session_id TEXT NOT NULL,
  period TEXT NOT NULL,
  human_minutes_likely INTEGER NOT NULL,
  verdict TEXT,
  corrected_minutes INTEGER,
  created_at BIGINT NOT NULL,
  reviewed_at BIGINT,
  CONSTRAINT human_time_checks_uq UNIQUE (surface, session_id, period)
);
