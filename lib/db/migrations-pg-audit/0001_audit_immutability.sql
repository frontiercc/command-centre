-- Postgres re-implementation of audit.db's append-only guarantee.
--
-- Mirrors lib/db/audit-db.ts's SQLite bootstrap (getAuditDb()) exactly: same
-- table + columns (see lib/db/schema-audit.ts's accessAuditLogPg), same CHECK
-- constraints on action/outcome, same trigger names (audit_no_update /
-- audit_no_delete) and the same "append-only" failure message. SQLite's
-- `RAISE(ABORT, 'access_audit_log is append-only')` becomes a plpgsql
-- `RAISE EXCEPTION` trigger function here.
--
-- This is NOT one of the numbered lib/db/migrations-pg/*.sql files generated
-- from schema.pg.ts — access_audit_log lives outside the main schema on
-- purpose (see the header comment in lib/db/schema-audit.ts), so it is applied
-- separately via applyAuditImmutabilityPg() in lib/db/audit-db.ts (called from
-- lib/db/client.ts's getAuditClient() postgres branch) and by the
-- testcontainers suite in test/audit-immutability-pg.test.ts.
--
-- Idempotent: CREATE TABLE/INDEX IF NOT EXISTS + CREATE OR REPLACE FUNCTION/
-- TRIGGER, safe to re-run against an already-provisioned database.

CREATE TABLE IF NOT EXISTS access_audit_log (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id    text NOT NULL,
  actor_email text NOT NULL,
  actor_ip    text,
  resource    text NOT NULL,
  action      text NOT NULL CHECK (action IN ('READ','WRITE','DELETE','EXPORT','SSO_LOGIN')),
  outcome     text NOT NULL CHECK (outcome IN ('success','denied','error','failure')),
  detail      text,
  occurred_at bigint NOT NULL DEFAULT extract(epoch from now())
);

CREATE INDEX IF NOT EXISTS idx_audit_actor    ON access_audit_log (actor_id);
CREATE INDEX IF NOT EXISTS idx_audit_resource ON access_audit_log (resource);
CREATE INDEX IF NOT EXISTS idx_audit_occurred ON access_audit_log (occurred_at);

CREATE OR REPLACE FUNCTION audit_reject() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'access_audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

-- CREATE OR REPLACE TRIGGER requires Postgres 14+ (this project targets 16 —
-- see lib/db/migrations-pg + test/helpers/pg.ts's postgres:16 container); it
-- keeps re-running this file idempotent without a separate DROP TRIGGER IF
-- EXISTS step.
CREATE OR REPLACE TRIGGER audit_no_update
  BEFORE UPDATE ON access_audit_log
  FOR EACH ROW EXECUTE FUNCTION audit_reject();

CREATE OR REPLACE TRIGGER audit_no_delete
  BEFORE DELETE ON access_audit_log
  FOR EACH ROW EXECUTE FUNCTION audit_reject();

